-- ============================================================
-- PostgreSQL schema: monitoring system
-- Based on the reviewed entity-relationship diagram
-- ============================================================
-- This file creates the 10 tables in the schema.
-- First create the database from pgAdmin or psql:
--   CREATE DATABASE success;
-- Then connect to it and execute this file.

BEGIN;

-- 1. Building
CREATE TABLE building (
    building_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(150) NOT NULL,
    address   VARCHAR(250)
);

-- 2. Zone
CREATE TABLE zone (
    zone_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT NOT NULL,
    name      VARCHAR(150) NOT NULL,
    floor        INTEGER,
    CONSTRAINT fk_zone_building
        FOREIGN KEY (building_id) REFERENCES building(building_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 3. Sensor type
CREATE TABLE sensor_type (
    sensor_type_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL UNIQUE,
    sampling_interval INTEGER NOT NULL,
    default_unit    VARCHAR(40),
    normal_minimum         NUMERIC(12,4),
    normal_maximum         NUMERIC(12,4),
    CONSTRAINT chk_sensor_type_sampling_interval
        CHECK (sampling_interval > 0),
    CONSTRAINT chk_sensor_type_normal_range
        CHECK (normal_minimum IS NULL OR normal_maximum IS NULL OR normal_minimum <= normal_maximum)
);

-- 4. Node
CREATE TABLE node (
    node_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                     VARCHAR(100) NOT NULL UNIQUE,
    name                     VARCHAR(150) NOT NULL,
    zone_id                    BIGINT NOT NULL,
    ip_address                         INET,
    local_storage_mb    NUMERIC(12,2),
    last_signal_received_at TIMESTAMPTZ,
    registered_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_node_zone
        FOREIGN KEY (zone_id) REFERENCES zone(zone_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_node_local_storage
        CHECK (local_storage_mb IS NULL OR local_storage_mb >= 0)
);

-- 5. Sensor
CREATE TABLE sensor (
    sensor_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(100) NOT NULL UNIQUE,
    primary_node_id  BIGINT NOT NULL,
    connection_type      VARCHAR(50),
    sensor_type_id     BIGINT NOT NULL,
    connection_address VARCHAR(250),
    CONSTRAINT fk_sensor_primary_node
        FOREIGN KEY (primary_node_id) REFERENCES node(node_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_sensor_sensor_type
        FOREIGN KEY (sensor_type_id) REFERENCES sensor_type(sensor_type_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 6. Role
CREATE TABLE app_role (
    role_code VARCHAR(50) PRIMARY KEY,
    name     VARCHAR(100) NOT NULL UNIQUE
);

-- 7. User
CREATE TABLE app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(254) NOT NULL UNIQUE,
    full_name  VARCHAR(200) NOT NULL,
    password_hash       TEXT NOT NULL,
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    role_code           VARCHAR(50) NOT NULL,
    CONSTRAINT fk_app_user_role
        FOREIGN KEY (role_code) REFERENCES app_role(role_code)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 8. Reading
CREATE TABLE reading (
    reading_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id                BIGINT NOT NULL,
    receiving_node_id         BIGINT NOT NULL,
    sequence_number         BIGINT,
    measured_at TIMESTAMPTZ NOT NULL,
    received_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    measured_value             NUMERIC(14,4) NOT NULL,
    CONSTRAINT fk_reading_sensor
        FOREIGN KEY (sensor_id) REFERENCES sensor(sensor_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_reading_receiving_node
        FOREIGN KEY (receiving_node_id) REFERENCES node(node_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_reading_sequence_number
        CHECK (sequence_number IS NULL OR sequence_number >= 0)
);

-- 9. Alert
CREATE TABLE alert (
    alert_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_uuid             VARCHAR(100) NOT NULL UNIQUE,
    reading_id              BIGINT NOT NULL,
    handled_by_user_id      BIGINT,
    alert_code           VARCHAR(100) NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_alert_reading
        FOREIGN KEY (reading_id) REFERENCES reading(reading_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_alert_handled_by_user
        FOREIGN KEY (handled_by_user_id) REFERENCES app_user(user_id)
        ON UPDATE CASCADE ON DELETE SET NULL
);

-- 10. Connectivity log
CREATE TABLE connectivity_log (
    connectivity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id         BIGINT NOT NULL,
    started_at     TIMESTAMPTZ NOT NULL,
    ended_at   TIMESTAMPTZ,
    CONSTRAINT fk_connectivity_log_node
        FOREIGN KEY (node_id) REFERENCES node(node_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_connectivity_log_dates
        CHECK (ended_at IS NULL OR ended_at >= started_at)
);

-- Indexes for relationships and frequent queries
CREATE INDEX idx_zone_building
    ON zone(building_id);

CREATE INDEX idx_node_zone
    ON node(zone_id);

CREATE INDEX idx_sensor_primary_node
    ON sensor(primary_node_id);

CREATE INDEX idx_sensor_sensor_type
    ON sensor(sensor_type_id);

CREATE INDEX idx_reading_sensor_measured_at
    ON reading(sensor_id, measured_at DESC);

CREATE INDEX idx_reading_receiving_node_received_at
    ON reading(receiving_node_id, received_at DESC);

CREATE INDEX idx_alert_generated_at
    ON alert(generated_at DESC);

CREATE INDEX idx_alert_handled_by_user
    ON alert(handled_by_user_id);

CREATE INDEX idx_connectivity_log_node_started_at
    ON connectivity_log(node_id, started_at DESC);

COMMIT;

-- Important:
-- * La columna event_uuid conserva el name del diagrama, pero es VARCHAR(100)
--   according to the agreed decision. You can rename it to event_code if it does not store a UUID.
-- * Store a secure hash (Argon2id or bcrypt) in password_hash, never plaintext.
-- * TIMESTAMPTZ stores instants and supports correct handling across time zones.
