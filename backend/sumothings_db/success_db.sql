-- ============================================================
-- PostgreSQL schema: SUMOTHINGS monitoring system
-- Based on: succ_sum_db_final_en.png
-- ============================================================
-- First create the database from pgAdmin or psql:
--   CREATE DATABASE success;
-- Then connect to it and execute this file.

BEGIN;

-- 1. Building
CREATE TABLE building (
    building_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_code VARCHAR(50)  NOT NULL UNIQUE,          -- JSON: building_code
    name          VARCHAR(150) NOT NULL,
    address       VARCHAR(250)
);

-- 2. Zone
CREATE TABLE zone (
    zone_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT       NOT NULL,
    zone_code   VARCHAR(50)  NOT NULL,                   -- JSON: zone_code
    name        VARCHAR(150) NOT NULL,
    floor       INTEGER,                                 -- JSON: floor
    CONSTRAINT fk_zone_building
        FOREIGN KEY (building_id) REFERENCES building(building_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_zone_building_code UNIQUE (building_id, zone_code)
);

-- 3. Node (bridge)
CREATE TABLE node (
    node_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_code        VARCHAR(100) NOT NULL UNIQUE,       -- JSON: node_code
    node_name        VARCHAR(150) NOT NULL,              -- JSON: node_name
    zone_id          BIGINT       NOT NULL,
    ip_address       INET,
    local_storage_mb NUMERIC(12,2),
    registered_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_node_zone
        FOREIGN KEY (zone_id) REFERENCES zone(zone_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_node_local_storage
        CHECK (local_storage_mb IS NULL OR local_storage_mb >= 0)
);

-- 4. Connectivity log
CREATE TABLE connectivity_log (
    connectivity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id         BIGINT      NOT NULL,
    started_at      TIMESTAMPTZ NOT NULL,
    ended_at        TIMESTAMPTZ,
    CONSTRAINT fk_connectivity_log_node
        FOREIGN KEY (node_id) REFERENCES node(node_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_connectivity_log_dates
        CHECK (ended_at IS NULL OR ended_at >= started_at)
);

-- 5. Sensor type
CREATE TABLE sensor_type (
    sensor_type_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    measurement_type VARCHAR(50)  NOT NULL UNIQUE,       -- JSON: measurement_type (temperature, air_quality, motion, electrical)
    name             VARCHAR(100) NOT NULL,
    sampling_interval INTEGER     NOT NULL,              -- seconds
    CONSTRAINT chk_sensor_type_sampling_interval
        CHECK (sampling_interval > 0)
);

-- 6. Sensor
CREATE TABLE sensor (
    sensor_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_code        VARCHAR(100) NOT NULL UNIQUE,     -- JSON: sensor_code
    primary_node_id    BIGINT       NOT NULL,
    sensor_type_id     BIGINT       NOT NULL,
    sensor_model       VARCHAR(100),                     -- JSON: sensor_model
    connection_type    VARCHAR(50),
    connection_address VARCHAR(250),
    CONSTRAINT fk_sensor_primary_node
        FOREIGN KEY (primary_node_id) REFERENCES node(node_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_sensor_sensor_type
        FOREIGN KEY (sensor_type_id) REFERENCES sensor_type(sensor_type_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 7. Sensor metric (one row per variable the JSON sends)
CREATE TABLE sensor_metric (
    metric_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_type_id  BIGINT       NOT NULL,
    metric_code     VARCHAR(100) NOT NULL,               -- e.g. average_avg_c, tvoc_avg_ppb, battery_low
    name            VARCHAR(150),
    unit            VARCHAR(40),
    normal_minimum  NUMERIC(14,4),
    normal_maximum  NUMERIC(14,4),
    CONSTRAINT fk_sensor_metric_sensor_type
        FOREIGN KEY (sensor_type_id) REFERENCES sensor_type(sensor_type_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_sensor_metric_type_code UNIQUE (sensor_type_id, metric_code),
    CONSTRAINT chk_sensor_metric_normal_range
        CHECK (normal_minimum IS NULL OR normal_maximum IS NULL OR normal_minimum <= normal_maximum)
);

-- 8. Ingest message (envelope of each received JSON)
CREATE TABLE ingest_message (
    message_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_uid         UUID         NOT NULL UNIQUE,    -- JSON: message_uid (deduplication)
    building_id         BIGINT       NOT NULL,
    message_type        VARCHAR(50)  NOT NULL,           -- JSON: message_type
    schema_version      VARCHAR(20)  NOT NULL,           -- JSON: schema_version
    sequence_number     BIGINT,                          -- JSON: sequence_number
    priority            VARCHAR(20)  NOT NULL,           -- JSON: priority
    quality             VARCHAR(20)  NOT NULL,           -- JSON: quality
    delivery_policy     VARCHAR(30),                     -- JSON: delivery_policy
    delivery_status     VARCHAR(30),                     -- JSON: delivery_status
    transport           VARCHAR(20),                     -- JSON: transport
    generated_at        TIMESTAMPTZ  NOT NULL,           -- JSON: generated_at
    sent_at             TIMESTAMPTZ,                     -- JSON: sent_at
    received_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,  -- set by the backend
    window_start        TIMESTAMPTZ,                     -- JSON: window.start
    window_end          TIMESTAMPTZ,                     -- JSON: window.end
    sample_count_bridge INTEGER,                         -- JSON: window.sample_count (total of the message)
    CONSTRAINT fk_ingest_message_building
        FOREIGN KEY (building_id) REFERENCES building(building_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_ingest_message_sequence
        CHECK (sequence_number IS NULL OR sequence_number >= 0),
    CONSTRAINT chk_ingest_message_window
        CHECK (window_start IS NULL OR window_end IS NULL OR window_end >= window_start),
    CONSTRAINT chk_ingest_message_sample_count
        CHECK (sample_count_bridge IS NULL OR sample_count_bridge >= 0)
);

-- 9. Reading (one row per variable of each sensor in each message)
CREATE TABLE reading (
    reading_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id          BIGINT        NOT NULL,
    sensor_id           BIGINT        NOT NULL,
    metric_id           BIGINT        NOT NULL,
    value               NUMERIC(14,4) NOT NULL,          -- booleans are stored as 0 / 1
    sample_count_sensor INTEGER,                         -- JSON: sample_count of the sensor
    CONSTRAINT fk_reading_message
        FOREIGN KEY (message_id) REFERENCES ingest_message(message_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_reading_sensor
        FOREIGN KEY (sensor_id) REFERENCES sensor(sensor_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_reading_metric
        FOREIGN KEY (metric_id) REFERENCES sensor_metric(metric_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_reading_message_sensor_metric UNIQUE (message_id, sensor_id, metric_id),
    CONSTRAINT chk_reading_sample_count
        CHECK (sample_count_sensor IS NULL OR sample_count_sensor >= 0)
);

-- 10. Role
CREATE TABLE app_role (
    role_code VARCHAR(50)  PRIMARY KEY,
    name      VARCHAR(100) NOT NULL UNIQUE
);

-- 11. User
CREATE TABLE app_user (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE,
    full_name     VARCHAR(200) NOT NULL,
    password_hash TEXT         NOT NULL,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    role_code     VARCHAR(50)  NOT NULL,
    CONSTRAINT fk_app_user_role
        FOREIGN KEY (role_code) REFERENCES app_role(role_code)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 12. Alert
CREATE TABLE alert (
    alert_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reading_id         BIGINT      NOT NULL,
    handled_by_user_id BIGINT,
    generated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_alert_reading
        FOREIGN KEY (reading_id) REFERENCES reading(reading_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_alert_handled_by_user
        FOREIGN KEY (handled_by_user_id) REFERENCES app_user(user_id)
        ON UPDATE CASCADE ON DELETE SET NULL
);

-- Indexes for relationships and frequent queries
CREATE INDEX idx_node_zone                    ON node(zone_id);
CREATE INDEX idx_sensor_primary_node          ON sensor(primary_node_id);
CREATE INDEX idx_sensor_sensor_type           ON sensor(sensor_type_id);
CREATE INDEX idx_sensor_metric_sensor_type    ON sensor_metric(sensor_type_id);
CREATE INDEX idx_ingest_message_building_time ON ingest_message(building_id, generated_at DESC);
CREATE INDEX idx_reading_sensor_metric        ON reading(sensor_id, metric_id);
CREATE INDEX idx_reading_metric               ON reading(metric_id);
CREATE INDEX idx_alert_generated_at           ON alert(generated_at DESC);
CREATE INDEX idx_alert_reading                ON alert(reading_id);
CREATE INDEX idx_alert_handled_by_user        ON alert(handled_by_user_id);
CREATE INDEX idx_connectivity_log_node_start  ON connectivity_log(node_id, started_at DESC);
CREATE INDEX idx_app_user_role                ON app_user(role_code);

COMMIT;

-- Notes:
-- * Store a secure hash (Argon2id or bcrypt) in password_hash, never plaintext.
-- * TIMESTAMPTZ stores instants and handles time zones correctly.
-- * message_uid is UUID: if the real messages do not carry valid UUIDs, change it to VARCHAR(100).
-- * The backend must check that reading.metric_id belongs to the sensor's type
--   (sensor_metric.sensor_type_id = sensor.sensor_type_id) and that all rows of the same
--   sensor and message carry the same sample_count_sensor.
